import assert from 'node:assert/strict';
import fs from 'node:fs';
import {feedbackFormURL,dictionaryProposalReport} from '../dist/dictionary-proposals.mjs';
import {addVocabulary} from './register-vocabulary.mjs';
import {Lexicon} from '../dist/lexicon.mjs';
const form={url:'https://docs.google.com/forms/d/e/test_form/viewform',kindEntry:'entry.123',detailsEntry:'entry.456',targetEntry:'entry.789',actualEntry:'entry.101',expectedEntry:'entry.102'};
const report=dictionaryProposalReport('試験用語','A&B #?');
const url=new URL(feedbackFormURL(form,report));
assert.equal(url.searchParams.get(form.kindEntry),'誤判定');
assert.equal(url.searchParams.get(form.targetEntry),'試験用語');
assert.equal(url.searchParams.get(form.actualEntry),report.actual);
assert.equal(url.searchParams.get(form.expectedEntry),report.expected);
assert.equal(url.searchParams.get(form.detailsEntry),'A&B #?');
assert.deepEqual([...url.searchParams.keys()],['usp',form.kindEntry,form.targetEntry,form.actualEntry,form.expectedEntry,form.detailsEntry]);
assert(!new URL(feedbackFormURL(form,dictionaryProposalReport('試験用語'))).searchParams.has(form.detailsEntry));
for(const word of ['', 'a'.repeat(81),'語\n語']) assert.throws(()=>dictionaryProposalReport(word));
assert.equal(new URL(feedbackFormURL(form)).searchParams.size,1);
assert.throws(()=>feedbackFormURL(form,{kind:'invalid'}));
assert.throws(()=>feedbackFormURL(form,{details:'a'.repeat(1201)}));
assert.throws(()=>feedbackFormURL(form,{target:123}));
assert.throws(()=>feedbackFormURL({...form,url:'https://example.com/forms/d/e/test/viewform'}));
assert.throws(()=>feedbackFormURL({...form,detailsEntry:form.kindEntry}));
assert.throws(()=>feedbackFormURL({...form,targetEntry:form.actualEntry}));
const issue='https://github.com/gtgtysys/chemical-proofreading-viewer/issues/1';
const additions=addVocabulary({schemaVersion:1,entries:[]},'検証化合勿',issue);
assert.equal(additions.entries[0].sourceIssue,issue);
assert.equal(addVocabulary({schemaVersion:1,entries:[]},'検証化合物',form.url).entries[0].sourceForm,form.url);
assert.throws(()=>addVocabulary(additions,'検証化合勿',issue));
assert.throws(()=>addVocabulary(additions,'語','https://example.com/issues/1'));
const base={entries:[{term:'検証化合物'}]},general={words:[]};
assert(new Lexicon(base,general).scan('検証化合勿').length);
assert.equal(new Lexicon(base,general,additions).scan('検証化合勿').length,0);
assert(new Lexicon(base,general,additions).scan('検証化合伍').length,'An added word must not suppress other typos');
const read=name=>JSON.parse(fs.readFileSync(new URL('../dist/dictionaries/'+name,import.meta.url),'utf8'));
assert.equal(read('default.json').patterns.length,0);
assert.equal(read('individual-rules.json').patterns.length,6);
assert(read('community-vocabulary.json').entries.some(e=>e.term==='水層'));
console.log('Dictionary proposals: URL privacy, validation, provenance and independent vocabulary passed');
