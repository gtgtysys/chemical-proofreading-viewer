import assert from 'node:assert/strict';
import fs from 'node:fs';
import {curriculumChecks} from '../dist/curriculum.mjs';
const policy=JSON.parse(fs.readFileSync(new URL('../dist/dictionaries/curriculum-review.json',import.meta.url),'utf8'));
const header='標準状態は0 ℃、1.013×10⁵ Paとする。';
const row=(text,pageNumber=1)=>({text,pageNumber,charMap:Array.from({length:text.length},(_,offset)=>({itemId:'p'+pageNumber,offset,total:text.length}))});
const check=text=>curriculumChecks([row(header+text)],policy);
for(const entry of policy.entries.filter(e=>e.kind==='term')) for(const term of entry.terms) {
  const hit=check(term).find(hit=>hit.ruleId===entry.id);
  assert(hit,term);
  assert.equal(hit.text,term);
  assert.equal(hit.suggestion,entry.preferred);
  assert(hit.reason.includes('断定'),'editorial preferences must not be presented as automatic errors');
}
for(const text of ['化合物','貴ガス','共有結合の結晶','両性金属','両性酸化物','水酸化鉄（Ⅲ）','アルデヒド','ケトン','活性化エネルギー','凝華','ヒドロキシ基','カルボキシ基','鏡像異性体']) assert.equal(check(text).length,0,text);
assert(check('気体から固体になる過程を昇華という。').some(h=>h.ruleId==='deposition'));
assert(check('昇華（気体→固体）').some(h=>h.ruleId==='deposition'));
assert.equal(check('固体から気体になる過程を昇華という。').length,0);
assert(check('BeとMgを除く2族元素がアルカリ土類金属である。').some(h=>h.ruleId==='alkaline-earth'));
assert.equal(check('アルカリ土類金属からBeとMgを除くこともある。').length,0);
assert.equal(check('2族元素すべてがアルカリ土類金属である。').length,0);
assert(check('3～11族元素が遷移元素である。').some(h=>h.ruleId==='transition-elements'));
assert(check('第3族から第11族が遷移元素である。').some(h=>h.ruleId==='transition-elements'));
assert.equal(check('3～12族が遷移元素である。').length,0);
assert.equal(check('3～11族が遷移元素である。12族元素は含める場合と含めない場合がある。').length,0);
assert(check('Fe（OH）₃を三価の弱塩基とする。').some(h=>h.ruleId==='ferric-hydroxide'));
assert(curriculumChecks([row('標準状態での気体を考える。')],policy).some(h=>h.ruleId==='standard-conditions'));
assert(curriculumChecks([row('10 ℃、1.013×10⁵ Paとする。')],policy).some(h=>h.ruleId==='standard-conditions'));
assert(curriculumChecks([row('気体について考える。'),row(header,2)],policy).some(h=>h.ruleId==='standard-conditions'),'conditions on a later page do not satisfy the introduction rule');
assert.equal(check('標準状態で測定する。').length,0);
const wrapped=row(header+'ヒドロキ\nシル基をもつ。');
const hit=curriculumChecks([wrapped],policy).find(h=>h.ruleId==='hydroxy');
assert.equal(hit.text,'ヒドロキ\nシル基');
assert.equal(wrapped.text.slice(hit.start,hit.start+hit.length),hit.text);
assert.equal(curriculumChecks([],policy).length,0);
assert.equal(new Set(policy.entries.map(e=>e.id)).size,policy.entries.length);
console.log(`Curriculum: all ${policy.entries.length} rules, conditional exceptions, introduction conditions and source offsets passed`);
