import assert from 'node:assert/strict';
import {textRows,textFlows,detectionIndex} from '../dist/detection.mjs';
import {Lexicon} from '../dist/lexicon.mjs';
const item=(id,text,left=20,top=20,role='本文',pageNumber=1)=>({id,text,role,pageNumber,size:10,emHeight:10,rect:{left,top,width:text.length*10,height:11.8}});
const reconstruct=items=>textFlows(textRows(items),items,[{pageNumber:1,viewport:{width:800,height:1000}},{pageNumber:2,viewport:{width:800,height:1000}}]);
const three=[item('a','ビニ'),item('b','ルアル',20,36),item('c','コールを考える。',20,52)];
const flow=reconstruct(three);
assert.equal(flow.length,1);
assert.equal(flow[0].text,'ビニルアルコールを考える。');
assert.equal(flow[0].charMap[2].itemId,'b');
assert.equal(flow[0].charMap[5].itemId,'c');
assert.equal(flow[0].charMap.length,flow[0].text.length);
const wrong=reconstruct([item('t1','中'),item('t2','和適',20,36),item('t3','定を行う。',20,52)])[0];
const wrongIndex=detectionIndex([wrong],true);
const hit=new Lexicon({entries:[{term:'中和滴定'}]},{words:[]}).scan(wrongIndex.text)[0];
assert.equal(hit.options[0].term,'中和滴定','a typo spanning three physical rows is still found');
assert.deepEqual([...new Set(wrongIndex.positionAt.slice(hit.start,hit.start+hit.length).filter(Boolean).map(p=>p.itemId))],['t1','t2','t3'],'highlight mapping covers every original row');
const zoomed=three.map(i=>({...i,emHeight:undefined,rect:Object.fromEntries(Object.entries(i.rect).map(([key,value])=>[key,value*1.35]))}));
assert.equal(reconstruct(zoomed)[0].text,flow[0].text,'PDF points must not be compared to displayed pixels');
const columns=reconstruct([item('l1','左段のビニ',20,20),item('r1','右段の中和',350,20),item('l2','ルアルコール。',20,36),item('r2','滴定。',350,36)]);
assert.deepEqual(columns.map(b=>b.text),['左段のビニルアルコール。','右段の中和滴定。']);
const heading=reconstruct([item('body','中和',20,20),item('title','見出し',20,36,'見出し'),item('tail','適定。',20,52)]);
assert.equal(heading.length,3);
assert.equal(reconstruct([item('label','鉛蓄電池',20,20),item('caption','図 3',20,44)]).length,2,'captions assembled from separate text items are a hard boundary');
assert.equal(reconstruct([item('reference','図3–3中の鏡',20,20),item('continuation','像異性体。',20,36)])[0].text,'図3–3中の鏡像異性体。','a figure reference within prose is not a caption');
assert(!heading.some(b=>b.text.includes('中和適定')));
const indented=reconstruct([item('first','前の段落の終わり。'),item('next','新しい段落',30,36)]);
assert.equal(indented.length,2);
const english=reconstruct([item('en1','organic'),item('en2','chemistry',20,36)]);
assert.equal(english[0].text,'organic'); // Prose reconstruction targets Japanese body text.
const pages=reconstruct([item('end','中和適',20,800),item('number','1',400,960,'ページ番号'),item('start','定を行う。',20,30,'本文',2)]);
const cross=pages.find(b=>b.text==='中和適定を行う。');
assert(cross);
assert.deepEqual(cross.pageNumbers,[1,2]);
assert.equal(detectionIndex([cross],true).positionAt[3].itemId,'start');
console.log('Text flows: logical prose, column separation, headings, sentence boundaries and PDF positions passed');
