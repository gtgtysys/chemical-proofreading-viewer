import assert from 'node:assert/strict';
import {mathVariables,unitSpans,mathText,scriptLabelSpans} from '../dist/math-roles.mjs';
import {schoolChecks} from '../dist/school-checks.mjs';
const variables=text=>mathVariables(text).map(m=>text.slice(m.start,m.start+m.length));
assert.deepEqual(variables('x + y = z'),['x','y','z']);
assert.deepEqual(variables('2x + 3y = 5'),['x','y']);
assert.deepEqual(variables('α + β = γ'),['α','β','γ']);
assert.deepEqual(variables('PV = nRT'),['P','V','n','R','T']);
assert.deepEqual(variables('ma=F'),['m','a','F']);
assert.equal(unitSpans('m').length,0);
assert.equal(unitSpans('ma=F').length,0);
assert.equal(unitSpans('3 m')[0].kind,'unit');
assert.equal(unitSpans('単位は m')[0].kind,'unit');
assert.deepEqual(variables('log(x) = y'),['x','y']);
for(const text of ['NaCl','H₂ + O₂ → H₂O','H₂ + O₂ = H₂O','C=O','図 A、B、C','sin']) assert.equal(mathVariables(text).length,0,text);
const check=(text,italic=false)=>schoolChecks([{text,charMap:Array.from({length:text.length},(_,offset)=>({itemId:'a',offset}))}],[{id:'a',font:'LMRoman10-Regular',italic}]);
assert.equal(check('x + y = z').filter(h=>h.label==='文字式の書体').length,3);
assert.equal(check('x + y = z',true).length,0);
assert.deepEqual(check('ma=F').map(h=>h.text),['m','a','F']);
assert.equal(check('ma=F',true).length,0);
for(const text of ['原子量：H=1.0，C=12','H₂C=CH−CH=CH₂','HF<NH₃<CH₄<H₂O','[A] = 2.0×10−4mol/L','[P]2 = [R]2']) assert.equal(check(text).length,0,text);
for(const text of ['原子量 H=1.0 O=16','H=1.0 O=16 Cu=64','O=C−R','(a)= (b)> (c)<','(i) ZnS [g/cm3]','C= [H2CO3] + [HCO ] + [CO ]','1J= 1C×1V']) assert.equal(check(text).length,0,text);
assert.equal(check('4 V = 0.10L').filter(h=>h.label==='単位の書体').length,0);
assert.deepEqual(unitSpans('10 mol/L m[g]').map(h=>'10 mol/L m[g]'.slice(h.start,h.start+h.length)),['mol','L','g']);
const item=(id,text,left,size=10,y=20)=>({id,text,pageNumber:1,size,emHeight:size,rect:{left,top:y-size,width:text.length*6,height:size*1.18},textOrigin:{x:left,y}});
const row=(text,ids)=>({text,charMap:ids.map(itemId=>itemId?{itemId,offset:0}:null)});
const spaced=row('x=y B',['x','eq','y',null,'B']);
const spacedItems=[item('x','x',0),item('eq','=',6),item('y','y',12),item('B','B',80)];
assert.equal(mathText(spaced,spacedItems),'x=y、B');
const indexed=row('FA=F',['F','A','eq','right']);
const indexItems=[item('F','F',0),item('A','A',6,7,22),item('eq','=',11),item('right','F',17)];
assert.deepEqual(scriptLabelSpans(indexed,indexItems),[{start:1,length:1}]);
assert.deepEqual(mathVariables(indexed.text,scriptLabelSpans(indexed,indexItems)).map(m=>indexed.text[m.start]),['F','F']);
assert.deepEqual(check('U = 5 V').map(h=>h.text),['U'],'V following a numerical value is a unit');
assert.equal(check('10 mol/L').length,0);
assert.equal(check('10 mol/L',true).filter(h=>h.label==='単位の書体').length,2);
console.log('Mathematical variables: contextual italic checks, units, functions and chemical species passed');
